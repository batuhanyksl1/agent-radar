// Bundles i18n/*.json into web/i18n.js, the one module both the plugin and the
// web page import. Run after editing or adding a locale: `node scripts/build-i18n.mjs`.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'i18n')
const en = JSON.parse(readFileSync(join(dir, 'en.json'), 'utf8'))
const keys = Object.keys(en)
const out = {}
for (const file of readdirSync(dir).filter(f => f.endsWith('.json')).sort()) {
  const lang = file.slice(0, -5)
  const m = JSON.parse(readFileSync(join(dir, file), 'utf8'))
  const missing = keys.filter(k => typeof m[k] !== 'string' || m[k] === '')
  const extra = Object.keys(m).filter(k => !(k in en))
  if (missing.length || extra.length) throw new Error(`${file}: missing ${missing.join(',') || '-'}; extra ${extra.join(',') || '-'}`)
  for (const k of keys) {
    const a = (en[k].match(/\{\w+\}/g) ?? []).sort().join()
    const b = (m[k].match(/\{\w+\}/g) ?? []).sort().join()
    if (a !== b) throw new Error(`${file}: placeholders differ in "${k}"`)
  }
  out[lang] = Object.fromEntries(keys.map(k => [k, m[k]]))
}
const NAMES = { en: 'English', tr: 'Türkçe', de: 'Deutsch', es: 'Español', fr: 'Français', it: 'Italiano', ja: '日本語', ko: '한국어',
  nl: 'Nederlands', pl: 'Polski', 'pt-BR': 'Português (Brasil)', ru: 'Русский', sv: 'Svenska', 'zh-Hans': '简体中文' }
const body = `// Generated by scripts/build-i18n.mjs from i18n/*.json. Do not edit by hand.
export const MESSAGES = ${JSON.stringify(out, null, 1)}

export const LANGUAGE_NAMES = ${JSON.stringify(Object.fromEntries(Object.keys(out).map(l => [l, NAMES[l] ?? l])), null, 1)}

/** Maps a locale tag ("tr_TR.UTF-8", "pt-PT", "zh-CN") to a bundled language; English when none fits. */
export function pickLang(tag) {
  const t = String(tag ?? '').replace(/\\..*$/, '').replace('_', '-').toLowerCase()
  if (!t) return 'en'
  const langs = Object.keys(MESSAGES)
  const exact = langs.find(l => l.toLowerCase() === t)
  if (exact) return exact
  const base = t.split('-')[0]
  return langs.find(l => l.toLowerCase() === base) ?? langs.find(l => l.toLowerCase().split('-')[0] === base) ?? 'en'
}

/** The message for \`key\` in \`lang\` (English when missing), with {name} placeholders filled from \`params\`. */
export function tr(lang, key, params) {
  const text = (MESSAGES[lang] ?? MESSAGES.en)[key] ?? MESSAGES.en[key] ?? key
  return params ? text.replace(/\\{(\\w+)\\}/g, (m, k) => (k in params ? String(params[k]) : m)) : text
}
`
writeFileSync(join(root, 'web', 'i18n.js'), body)
console.log(`web/i18n.js: ${Object.keys(out).length} languages, ${keys.length} keys`)
